#!/usr/bin/env python3
"""build/showbill_calls.h: for each call in the bank (build/call-index.json order), the player it names
(only players with art) and its family. Source of names: review CALL-FIGURE-ASSIGNMENTS (owner-confirmed)."""
import json, sys, pathlib
idx = json.load(open(sys.argv[1]))["calls"]; a = json.load(open(sys.argv[2])); out = pathlib.Path(sys.argv[3])
FIG = {"Leon": 1, "Eldon": 2, "Al": 3, "Herb": 4, "Tiny": 5, "Tommy": 6, "Junior": 7, "Noel": 8, "Jimmy": 9}
FAM = {"signature_aah_haa": 1, "yeah": 2, "named_player_cue": 3}
by = {c["id"]: next((FIG[n] for n in c["names"] if n in FIG), 0) for c in a["calls"] if c["status"] == "assign"}
fig = [by.get(c["id"], 0) for c in idx]; fam = [FAM.get(c.get("family", ""), 0) for c in idx]
out.write_text("/* Generated by tools/showbill_calls.py */\n#ifndef SW_SHOWBILL_CALLS_H\n#define SW_SHOWBILL_CALLS_H\n#include <stdint.h>\n"
  f"#define SB_CALLS {len(idx)}u\nstatic const uint8_t sb_call_figure[SB_CALLS]={{{','.join(map(str, fig))}}};\n"
  f"static const uint8_t sb_call_family[SB_CALLS]={{{','.join(map(str, fam))}}};\n#endif\n")
print(len(idx), "calls,", sum(1 for f in fig if f), "name a drawn player")
