"""Exact acoustic-table bank. Offline build artifact; never writes a device."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
TABLES = [
    ('sw_fiddle_pcm', 'timbres.h', 4, 7200),
    ('sw_fiddle_short_pcm', 'timbres.h', 8, 3600),
    ('sw_upright_pcm', 'rhythm_timbres.h', 2, 4800),
    ('sw_piano_pcm', 'timbres.h', 2, 6000),
]
SLOT = 81920
HEADER = 512


def wrap_arrays(text, names):
    """Keep embedded initializers exact; opt-in builds use typed bank pointers."""
    for name in names:
        pattern = r'(static const uint8_t ' + name + r'\[(\d+)\]\[([^]]+)\]\s*=\s*\{.*?\};)'
        found = re.search(pattern, text, re.S)
        if not found:
            raise ValueError('Missing PCM declaration: ' + name)
        if '#ifdef SW_WITH_TIMBRE_BANK\nextern const uint8_t (*' + name in text:
            continue
        text = text[:found.start()] + (
            '#ifdef SW_WITH_TIMBRE_BANK\nextern const uint8_t (*' + name +
            ')[' + found[3] + '];\n#else\n' + found[1] + '\n#endif'
        ) + text[found.end():]
    return text


def build(root=ROOT):
    entries = []
    payload = bytearray()
    for index, (name, header, rows, length) in enumerate(TABLES, 1):
        source = root / 'src' / header
        found = re.search(r'static const uint8_t ' + name + r'\[[^;]*?=\s*\{(.*?)\};', source.read_text(), re.S)
        if not found:
            raise ValueError(name)
        numbers = [int(n) for n in re.findall(r'-?\d+', found[1])]
        if len(numbers) != rows * length or not all(0 <= n <= 255 for n in numbers):
            raise ValueError('Invalid table shape: ' + name)
        blob = bytes(numbers)
        entries.append({'id': index, 'symbol': name, 'offset': HEADER + len(payload),
                        'bytes': len(blob), 'rows': rows, 'row_bytes': length,
                        'crc32': zlib.crc32(blob), 'sha256': hashlib.sha256(blob).hexdigest(),
                        'source': str(source.relative_to(root)),
                        'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest()})
        payload.extend(blob)
    assert len(payload) == 79200
    header = bytearray(HEADER)
    struct.pack_into('<4sIIIII', header, 0, b'BBTB', 1, HEADER + len(payload),
                     zlib.crc32(payload), len(entries), len(payload))
    for index, entry in enumerate(entries):
        struct.pack_into('<IIII', header, 32 + index * 16,
                         entry['id'], entry['offset'], entry['bytes'], entry['crc32'])
    image = bytes(header + payload + b'\xff' * (SLOT - HEADER - len(payload)))
    report = {'schema': 'bb-bob-timbre-bank/v1', 'format': 'BBTB v1; exact existing companded bytes',
              'slot_bytes': SLOT, 'header_bytes': HEADER, 'pcm_bytes': len(payload),
              'used_bytes': HEADER + len(payload), 'padding_bytes': SLOT - HEADER - len(payload),
              'header_crc32': zlib.crc32(header), 'payload_crc32': zlib.crc32(payload),
              'bank_sha256': hashlib.sha256(image).hexdigest(), 'entries': entries,
              'quantization_changed': False, 'device_contacted': False,
              'installed': False, 'install_permitted': False}
    contract = ('/* SPDX-License-Identifier: GPL-3.0-only; generated by tools/timbre_bank.py. */\n'
                '#ifndef SW_TIMBRE_BANK_DATA_H\n#define SW_TIMBRE_BANK_DATA_H\n' +
                '#define SW_TB_HEADER_CRC 0x%08xu\n#define SW_TB_PAYLOAD_CRC 0x%08xu\n' %
                (report['header_crc32'], report['payload_crc32']) + '#endif\n')
    return image, report, contract


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build/timbre-r40')
    parser.add_argument('--write-contract', action='store_true', help='Explicitly update the source compatibility fingerprint')
    args = parser.parse_args()
    image, report, contract = build()
    path = ROOT / 'src/timbre_bank_data.h'
    if args.write_contract:
        path.write_text(contract)
    elif not path.exists() or path.read_text() != contract:
        raise ValueError('PCM compatibility contract differs; review changes before --write-contract')
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / 'timbres.bank').write_bytes(image)
    (args.output / 'timbres.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps({k: report[k] for k in ['slot_bytes', 'pcm_bytes', 'bank_sha256', 'quantization_changed']}, indent=2))


if __name__ == '__main__':
    main()
